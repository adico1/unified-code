"""Declaration-driven generation tests.

Canonical JSON is the authoritative declaration input. These tests prove the
JSON path directly — deterministic rebuild, source-formatting independence, and
a stable canonical symbolic hash — rather than measuring JSON against the .py
form. Legacy .py equivalence is a migration-only, opt-in check.
"""

from __future__ import annotations

